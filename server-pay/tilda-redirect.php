<?php
/**
 * Старые адреса товаров Tilda — на их нынешние страницы.
 *
 * Правило в .htaccess сперва пробует найти страницу по slug из старого
 * адреса; это быстро и обходится без PHP. Но Tilda переводила «ы» в "i", а
 * мы в "y", поэтому у каждого пятого товара slug разошёлся, и правило
 * промахивалось — человек и поисковый робот попадали в раздел вместо
 * карточки, а накопленные позиции товара уходили в никуда.
 *
 * Сюда приходят только такие промахи. Uid товара при переезде не менялся,
 * по нему промахнуться нельзя.
 */

declare(strict_types=1);

$uid = (string)($_GET['uid'] ?? '');
$target = '/catalog/';

if (preg_match('/^[0-9]{6,20}$/', $uid)) {
    $map = json_decode((string)@file_get_contents(__DIR__ . '/../api/tilda-map.json'), true);
    if (is_array($map) && isset($map[$uid]) && is_string($map[$uid])) {
        $target = $map[$uid];
    } elseif (preg_match('/^[a-z0-9_-]{2,40}$/', (string)($_GET['sec'] ?? ''), $m)) {
        // Товара нет в карте (сняли с продажи давно) — ведём в его раздел:
        // это ближе к тому, что человек искал, чем общий каталог.
        $target = '/' . $m[0] . '/';
    }
}

// 301, а не 302: адрес сменился навсегда, и поисковик должен перенести на
// новую страницу всё, что накопила старая.
header('Location: ' . $target, true, 301);
header('Cache-Control: max-age=86400');
exit;
